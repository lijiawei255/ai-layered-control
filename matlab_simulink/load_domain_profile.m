function P = load_domain_profile(name)
%LOAD_DOMAIN_PROFILE Canonical physical benchmark and three interface mappings.
if nargin < 1, name = 'industrial'; end
names = {'industrial','edge_vla','neuromodulation'};
titles = {'Industrial WAAM / PLC servo','Edge VLA / fast-slow robotics', ...
          'Closed-loop neuromodulation aDBS / SCS'};
idx = find(strcmp(name,names),1);
if isempty(idx), error('Unknown domain: %s',name); end
P.kind = name; P.name = titles{idx}; P.dt = .001;
P.nominal = struct('J',.01,'b',.06,'k',.3,'fc',.6,'fs',1.);
P.cfg = struct('dt_s',.001,'outer_timeout_s',.35, ...
    'max_physics_residual',1.,'residual_clear_ratio',.5, ...
    'min_ai_confidence',.01,'confidence_clear_ratio',.02, ...
    'state_safety_limit',1.,'safety_trip_ratio',.9,'safety_clear_ratio',.75, ...
    'safety_predict_s',.025,'u_max',20.,'u_slew_max_per_s',2000., ...
    'blend_alpha',.3,'integ_limit',.5,'windup_tau_s',.1, ...
    'min_dwell_ticks',150,'ood_recovery_cooldown_ticks',300, ...
    'kp',[60;110;8;2],'kd',[1.2;1.5;.8;.35], ...
    'ki',[60;300;2;0],'ff_scale',[1;1;1;0]);
P.baseline = [110,1.5,300]; % Kp, Kd, Ki; no transfer smoothing.
P.feature_scales = [.5,20,.006,.005];
P.classifier = []; P.policy = [];
P.units = struct('state','rad','input','N m','contact','N');
% Each application supplies its own measured states and actuator mapping.
% Numeric results use the common mechanical test fixture.
end